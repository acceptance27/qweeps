function buildDynamicInnerLesson(spec: NonSummaryBlockSpec): SubFunctionLesson {
  return {
    id: spec.id,
    parentFunctionId: spec.parentFunctionId,
    parentBeatNumber: spec.parentBeatNumber,
    parentNodeId: spec.id,
    functionName: spec.blockName,
    signature: spec.signature,
    fileName: spec.fileName,
    codebaseRange: spec.codebaseRange,
    totalModuleLines: 40,
    summary: `${spec.goalTitle} ${spec.goalText}`,
    sidebarInputs: spec.inputs,
    codeLines: spec.innerSteps.map((st, idx) => {
      const prevStep = idx > 0 ? spec.innerSteps[idx - 1] : null;
      const firstInput = spec.inputs[0];
      return {
        lineNumber: spec.baseLine + idx,
        text: st.atName,
        explanation: `${st.goalText} -> ${st.resultText}`,
        atName: st.atName,
        goalText: st.goalText,
        inputLabel: prevStep
          ? `${prevStep.atName} input`
          : firstInput
          ? `${firstInput.name} input`
          : '@input',
        inputValue: prevStep
          ? prevStep.resultText
          : firstInput
          ? firstInput.value
          : '',
        outputLabel: `${st.atName} output`,
        resultText: st.resultText,
      };
    }),
    graph: spec.graph,
    steps: spec.steps,
  };
}

const BUILT_INNER_LESSONS: Record<string, SubFunctionLesson> = Object.fromEntries(
  Object.entries(NON_SUMMARY_SPECS).map(([k, v]) => [k, buildDynamicInnerLesson(v)])
);

export function getInnerFunctionLesson(id: string): SubFunctionLesson | null {
  const cleanId = (id || '').replace(/^(generated-)+/, '');
  return BUILT_INNER_LESSONS[cleanId] ?? null;
}

export function getNonSummarySpec(id: string): NonSummaryBlockSpec | null {
  const cleanId = (id || '').replace(/^(generated-)+/, '');
  return NON_SUMMARY_SPECS[cleanId] ?? null;
}

export const ALL_INNER_FUNCTION_LESSONS: Record<string, SubFunctionLesson> = BUILT_INNER_LESSONS;
